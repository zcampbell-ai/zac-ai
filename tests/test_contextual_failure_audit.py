@pytest.mark.parametrize("raw,expected_hash", list(LEGACY_GOLDENS.values()))
def test_prechange_writer_golden_bytes_and_hashes(raw, expected_hash):
    from zacai.ingestion.artifact_store import content_hash_of

    event = ContextualAuditEvent.model_validate_json(raw)
    encoded = canonical_bytes(event.model_dump(mode="json"))
    assert encoded == raw
    assert content_hash_of(encoded) == expected_hash


