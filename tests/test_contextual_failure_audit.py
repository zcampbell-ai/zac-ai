def legacy_data():
    return {
        "format": "zac-contextual-run-audit-v1",
        "audit_event_id": str(UUID(int=1)), "run_id": str(UUID(int=2)),
        "task_id": str(UUID(int=3)), "builder_id": str(UUID(int=4)),
        "recorded_at": datetime(2026, 10, 5, tzinfo=UTC).isoformat().replace("+00:00", "Z"),
        "trust_boundary": "BRAINSTORM", "data_classification": "CONFIDENTIAL",
        "stage": "RUN_FAILED", "request_digest": "a" * 64,
        "context_digest": "b" * 64, "model_digest": "c" * 64,
        "route": {"provider_id": "invented", "model_id": "fixture", "runtime_id": "test"},
        "packet_source_id": None, "packet_digest": None,
    }


def test_prior_failure_audit_round_trips_byte_exactly():
    data = legacy_data()
    event = ContextualAuditEvent.model_validate(data)
    assert event.failure_step is None
    assert canonical_bytes(event.model_dump(mode="json")) == canonical_bytes(data)
    assert "failure_step" not in event.model_dump()
    assert "failure_step" not in event.model_dump_json()


@pytest.mark.parametrize("step", list(ContextualFailureStep))
def test_closed_failure_operation_round_trips(step):
    before = {ContextualFailureStep.REQUEST_AUDIT, ContextualFailureStep.CLAIM,
              ContextualFailureStep.RUNTIME_PREFLIGHT, ContextualFailureStep.DISPATCH_AUDIT,
              ContextualFailureStep.DISPATCH_CLOCK_START}
    after = {ContextualFailureStep.CAPTURE_SESSION_CLOSE, ContextualFailureStep.PROTECTION, ContextualFailureStep.RECOVERY_RECEIPT_VALIDATION,
             ContextualFailureStep.PACKET_READ, ContextualFailureStep.PACKET_VALIDATION,
             ContextualFailureStep.METADATA_ACCESS_CHECK, ContextualFailureStep.RELEASE_LATENCY_CHECK}
    data = legacy_data() | {"failure_step": step.value, "dispatch_attempted": step not in before}
    if step in after:
        data.update(packet_source_id=str(UUID(int=5)), packet_digest="d" * 64)
    event = ContextualAuditEvent.model_validate(data)
    assert event.failure_step == step
    assert canonical_bytes(event.model_dump(mode="json")) == canonical_bytes(data)


@pytest.mark.parametrize("stage", [ContextualAuditStage.REQUEST_PREPARED,
                                     ContextualAuditStage.DISPATCH_PREPARED,
                                     ContextualAuditStage.PACKET_CAPTURED])
def test_nonfailure_cannot_assert_failure_operation(stage):
    data = legacy_data() | {"stage": stage.value, "failure_step": "GENERATION", "dispatch_attempted": True}
    if stage == ContextualAuditStage.PACKET_CAPTURED:
        data.update(packet_source_id=str(uuid4()), packet_digest="d" * 64)
    with pytest.raises(ValidationError):
        ContextualAuditEvent.model_validate(data)


def test_private_free_text_cannot_enter_failure_operation():
    with pytest.raises(ValidationError):
        ContextualAuditEvent.model_validate(legacy_data() | {"failure_step": "PRIVATE response text"})


